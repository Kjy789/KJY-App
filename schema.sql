-- Helper Function to check if current user is owner
CREATE OR REPLACE FUNCTION public.is_owner()
RETURNS BOOLEAN AS $$
BEGIN
    RETURN EXISTS (
        SELECT 1 FROM public.profiles
        WHERE id = auth.uid() AND role = 'owner'
    );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Profiles Policies
CREATE POLICY "Public profiles are viewable by authenticated users" 
    ON public.profiles FOR SELECT TO authenticated USING (true);

CREATE POLICY "Users can update own profile" 
    ON public.profiles FOR UPDATE TO authenticated USING (auth.uid() = id);

-- Products Policies
CREATE POLICY "Authenticated users can read products" 
    ON public.products FOR SELECT TO authenticated USING (true);

CREATE POLICY "Authenticated users can insert products" 
    ON public.products FOR INSERT TO authenticated WITH CHECK (true);

CREATE POLICY "Authenticated users can update products" 
    ON public.products FOR UPDATE TO authenticated USING (true);

CREATE POLICY "Owner can delete products" 
    ON public.products FOR DELETE TO authenticated USING (public.is_owner());

-- Purchase Receipts Policies
CREATE POLICY "Authenticated users can select receipts"
    ON public.purchase_receipts FOR SELECT TO authenticated USING (true);

CREATE POLICY "Authenticated users can insert receipts"
    ON public.purchase_receipts FOR INSERT TO authenticated WITH CHECK (true);

CREATE POLICY "Owner can update receipts"
    ON public.purchase_receipts FOR UPDATE TO authenticated USING (public.is_owner());

-- Cost History Policies (Owner Only)
CREATE POLICY "Owner can access cost history"
    ON public.cost_history FOR ALL TO authenticated USING (public.is_owner());


