-- 1. Create EXTENSIONS if needed
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 2. PROFILES TABLE (User roles: 'owner' or 'staff')
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    email TEXT UNIQUE NOT NULL,
    full_name TEXT,
    role TEXT NOT NULL DEFAULT 'staff' CHECK (role IN ('owner', 'staff')),
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Trigger to automatically create profile on signup
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO public.profiles (id, email, full_name, role)
    VALUES (
        NEW.id,
        NEW.email,
        COALESCE(NEW.raw_user_meta_data->>'full_name', NEW.email),
        COALESCE(NEW.raw_user_meta_data->>'role', 'staff')
    );
    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();


-- 3. PRODUCTS TABLE
CREATE TABLE IF NOT EXISTS public.products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku TEXT UNIQUE,
    name TEXT NOT NULL,
    category TEXT,
    cost_price NUMERIC(12, 2) DEFAULT 0.00 NOT NULL,
    sale_price NUMERIC(12, 2) DEFAULT 0.00 NOT NULL,
    stock_qty INT DEFAULT 0 NOT NULL,
    front_stock INT DEFAULT 0 NOT NULL,
    warehouse_stock INT DEFAULT 0 NOT NULL,
    location_code TEXT,
    image_url TEXT,
    location_image_url TEXT,
    status TEXT DEFAULT 'active' CHECK (status IN ('active', 'pending', 'archived')),
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Index for fast real-time search
CREATE INDEX IF NOT EXISTS idx_products_name ON public.products (name);
CREATE INDEX IF NOT EXISTS idx_products_sku ON public.products (sku);
CREATE INDEX IF NOT EXISTS idx_products_category ON public.products (category);
CREATE INDEX IF NOT EXISTS idx_products_location ON public.products (location_code);


-- 4. LOCATIONS TABLE (โกดัง / ชั้นวาง)
CREATE TABLE IF NOT EXISTS public.locations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT UNIQUE NOT NULL,
    name TEXT NOT NULL,
    description TEXT,
    image_url TEXT,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);


-- 5. PURCHASE RECEIPTS TABLE (บิลสั่งซื้อ)
CREATE TABLE IF NOT EXISTS public.purchase_receipts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_no TEXT,
    supplier_name TEXT,
    receipt_date DATE DEFAULT CURRENT_DATE,
    total_amount NUMERIC(12, 2) DEFAULT 0.00,
    image_url TEXT,
    ocr_raw_json JSONB,
    ocr_status TEXT DEFAULT 'pending' CHECK (ocr_status IN ('pending', 'completed', 'failed')),
    created_by UUID REFERENCES public.profiles(id),
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);


-- 6. RECEIPT ITEMS TABLE (รายการในบิล)
CREATE TABLE IF NOT EXISTS public.receipt_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_id BIGINT REFERENCES public.purchase_receipts(id) ON DELETE CASCADE,
    product_id BIGINT REFERENCES public.products(id) ON DELETE SET NULL,
    ocr_name TEXT NOT NULL,
    qty INT DEFAULT 1 NOT NULL,
    unit_cost NUMERIC(12, 2) DEFAULT 0.00 NOT NULL,
    line_total NUMERIC(12, 2) GENERATED ALWAYS AS (qty * unit_cost) STORED,
    match_status TEXT DEFAULT 'matched' CHECK (match_status IN ('matched', 'new_product', 'pending')),
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);


-- 7. COST HISTORY TABLE (ประวัติต้นทุนสินค้า)
CREATE TABLE IF NOT EXISTS public.cost_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT REFERENCES public.products(id) ON DELETE CASCADE NOT NULL,
    receipt_id BIGINT REFERENCES public.purchase_receipts(id) ON DELETE SET NULL,
    old_cost NUMERIC(12, 2) DEFAULT 0.00,
    new_cost NUMERIC(12, 2) NOT NULL,
    changed_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);


